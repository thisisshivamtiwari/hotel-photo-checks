"""Measure the legibility gate on made images of known text size. Writes results/legibility.json and the README table.

Three sets, all generated by scripts/legibility_fixtures.py: rate-card pages at 200 dpi, as a 150 dpi phone photo and
as a 100 dpi 1-bit fax (body capitals about 21, 16 and 11 px); the first 10 source photos with a caption stamped at
36, 20 and 10 px capitals; and the 40 source photos as they are, which carry no text."""

import json
import re
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
import legibility_fixtures as fx  # noqa: E402

from photo_checks import legibility, rules  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results" / "legibility.json"
EXPECT = {"clean": "legible", "phone": "legible", "fax": "too_small"}
EXPECT |= {"cap36": "legible", "cap20": "legible", "cap10": "too_small"}


def run() -> dict:
    fixdir = ROOT / "results" / "legibility-fixtures"
    rows = fx.make(fixdir)
    t0 = time.time()
    conds: dict[str, dict] = {}
    for row in rows:
        full = rules.load(fixdir / row["file"]).full
        g = legibility.gate(full)
        m = legibility.measure(full)  # the raw measure, also on photos, for the record
        blank = {"kind": row["kind"], "cap_px": row["cap_px"], "n": 0, "gate": {}, "raw_correct": 0, "heights": []}
        c = conds.setdefault(row["cond"], blank)
        c["n"] += 1
        c["gate"][g["status"]] = c["gate"].get(g["status"], 0) + 1
        c["raw_correct"] += m.status == EXPECT[row["cond"]]
        if m.median_height is not None:
            c["heights"].append(m.median_height)
    sources = {"n": 0, "gate": {}, "raw_lines_found": 0}
    for p in fx.SOURCES:
        full = rules.load(p).full
        g = legibility.gate(full)
        sources["n"] += 1
        sources["gate"][g["status"]] = sources["gate"].get(g["status"], 0) + 1
        sources["raw_lines_found"] += legibility.measure(full).lines > 0
    for c in conds.values():
        hs = sorted(c.pop("heights"))
        c["median_height_px"] = hs[len(hs) // 2] if hs else None
    secs = time.time() - t0
    return {"floor_px": legibility.FLOOR_PX, "fixtures": len(rows), "conditions": conds, "text_free_sources": sources,
            "seconds_per_image": round(secs / (len(rows) + sources["n"]), 2)}  # fmt: skip


def table(r: dict) -> str:
    c = r["conditions"]
    lines = [
        "| Image | Capitals | Gate says | Raw measure right | Median glyph height found |",
        "|---|---|---|---|---|",
    ]
    names = {"clean": "Rate card, 200 dpi", "phone": "Rate card as a 150 dpi phone photo", "fax": "Rate card as a 100 dpi fax"}
    names |= {"cap36": "Photo with a 36 px caption", "cap20": "Photo with a 20 px caption", "cap10": "Photo with a 10 px caption"}
    for k, name in names.items():
        v = c[k]
        gate = ", ".join(f"{s} {n}/{v['n']}" for s, n in sorted(v["gate"].items()))
        h = f"{v['median_height_px']:.0f} px" if v["median_height_px"] is not None else "-"
        lines.append(f"| {name} | {v['cap_px']} px | {gate} | {v['raw_correct']}/{v['n']} | {h} |")
    s = r["text_free_sources"]
    gate = ", ".join(f"{k} {n}/{s['n']}" for k, n in sorted(s["gate"].items()))
    clean = s["n"] - s["raw_lines_found"]
    lines.append(f"| The 40 source photos (no text) | none | {gate} | {clean}/{s['n']} find no line | - |")
    return "\n".join(lines)


def write_readme(r: dict, path: Path = ROOT / "README.md") -> None:
    text = path.read_text()
    block = f"<!-- legibility:start -->\n{table(r)}\n<!-- legibility:end -->"
    new = re.sub(r"<!-- legibility:start -->.*?<!-- legibility:end -->", lambda _: block, text, flags=re.S)
    path.write_text(new)


if __name__ == "__main__":
    r = run()
    OUT.write_text(json.dumps(r, indent=1) + "\n")
    write_readme(r)
    print(table(r))
    print(json.dumps({k: v for k, v in r.items() if k != "conditions"}))
